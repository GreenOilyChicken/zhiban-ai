# ── 构建 alias 到 key 的索引 ─────────────────────────────

_SURGERY_INDEX: Dict[str, str] = {}
for _key, _val in _REHAB_PLANS.items():
    for _alias in _val.get("aliases", []):
        _SURGERY_INDEX[_alias.lower()] = _key


def _match_surgery(query: str) -> Optional[str]:
    """从查询中匹配手术类型"""
    query_lower = query.lower()
    for alias, key in _SURGERY_INDEX.items():
        if alias in query_lower:
            return key
    return None


def _format_rehab_plan(surgery_key: str) -> str:
    """格式化康复计划输出"""
    plan = _REHAB_PLANS[surgery_key]

    lines = []
    lines.append("══════════════════════════════════════")
    lines.append(f"  {plan['surgery_name']} 术后康复计划")
    lines.append("══════════════════════════════════════")
    lines.append("")
    lines.append("【康复总览】")
    lines.append(f"  {plan['overview']}")
    lines.append("")

    # 禁忌注意事项
    lines.append("【禁忌与注意事项】")
    for i, c in enumerate(plan["contraindications"], 1):
        lines.append(f"  {i}. {c}")
    lines.append("")

    # 分阶段计划
    for stage in plan["stages"]:
        lines.append(f"━━━ {stage['stage']} ━━━")
        lines.append(f"  康复目标：{stage['goals']}")
        lines.append("")
        lines.append("  训练项目：")
        for j, ex in enumerate(stage["exercises"], 1):
            lines.append(f"    ({j}) {ex}")
        lines.append(f"  活动与移动：{stage['mobility']}")
        lines.append(f"  注意事项：{stage['precautions']}")
        lines.append("")

    # 紧急信号
    lines.append("【紧急联系方式】")
    lines.append("  · 急救电话：120")
    lines.append("  · 心理援助热线：400-161-9995")
    lines.append("══════════════════════════════════════")
    lines.append("")
    lines.append("⚠️ 以上康复计划仅供参考，具体训练方案请遵康复医师/治疗师指导。")
    lines.append("  如训练中出现剧烈疼痛、肿胀加重、关节弹响、胸闷气短，请立即停止并就诊。")

    return "\n".join(lines)


