# ── 关键词匹配 ──────────────────────────────────────────

def _match_story(site_name: str) -> Optional[dict]:
    """匹配文化故事"""
    query = site_name.strip().lower()

    # 精确匹配
    for info in CULTURAL_STORIES.values():
        for alias in info["names"]:
            if query == alias.lower():
                return info

    # 包含匹配
    for info in CULTURAL_STORIES.values():
        for alias in info["names"]:
            if alias.lower() in query or query in alias.lower():
                return info

    # 关键词匹配
    for key, info in CULTURAL_STORIES.items():
        if key in query or query in key:
            return info

    return None


def _format_story(info: dict, theme: str) -> str:
    """格式化文化故事输出"""
    stories = info.get("stories", {})

    # 选择主题
    theme_map = {
        "历史": "历史",
        "建筑": "建筑",
        "传说": "传说",
        "人物": "人物",
        "general": None,
        "全部": None,
        "all": None,
        "": None,
    }

    selected_theme = theme_map.get(theme.lower() if theme else "", None)

    lines = []
    lines.append("【%s的文化故事】" % info["name"])
    lines.append("地点：%s" % info.get("location", ""))
    lines.append("年代：%s" % info.get("period", ""))
    lines.append("")

    if selected_theme and selected_theme in stories:
        # 只讲选定主题
        lines.append("---- %s ----" % selected_theme)
        lines.append(stories[selected_theme])
    else:
        # 讲所有主题
        for t, content in stories.items():
            lines.append("---- %s ----" % t)
            lines.append(content)
            lines.append("")

    lines.append("")
    lines.append("希望这些故事能让您在游览时多一份感悟。")
    lines.append("历史的温度，需要我们用心去体会。")

    return "\n".join(lines)


# ── 工具函数 ────────────────────────────────────────────

def cultural_story(site_name: str, theme: str = "general") -> str:
    """
    讲述历史景点的文化故事

    参数：
        site_name: 景点名称（如故宫、长城、兵马俑等）
        theme: 故事主题，可选值：历史/建筑/传说/人物/general（全部）
    """
    if not site_name or not site_name.strip():
        return "请告诉我您想了解哪个景点的文化故事，例如：故宫、长城、兵马俑、西湖等。"

    query = site_name.strip()
    logger.info("文化故事查询: site=%s, theme=%s" % (query, theme))

    matched = _match_story(query)
    if matched:
        logger.info("文化故事命中: %s" % matched["name"])
        return _format_story(matched, theme)

    # 没匹配到
    known = "、".join(info["name"] for info in CULTURAL_STORIES.values())
    return (
        "抱歉，目前没有找到\"%s\"的文化故事。\n\n"
        "目前内置文化故事覆盖的景点包括：\n%s\n\n"
        "您可以尝试查询以上景点。我们也在持续更新内容，感谢您的理解。\n\n"
        "提示：如果您想了解的景点不在列表中，"
        "也可以直接告诉我您感兴趣的内容，我会尽力为您讲述。"
        % (query, known)
    )


