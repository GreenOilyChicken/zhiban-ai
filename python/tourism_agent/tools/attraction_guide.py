# ── 关键词匹配 ──────────────────────────────────────────

def _match_fallback(attraction_name: str) -> Optional[dict]:
    """在内置知识库中匹配景点"""
    query = attraction_name.strip().lower()

    # 精确匹配
    for info in FALLBACK_ATTRACTIONS.values():
        for alias in info["names"]:
            if query == alias.lower():
                return info

    # 包含匹配
    for info in FALLBACK_ATTRACTIONS.values():
        for alias in info["names"]:
            if alias.lower() in query or query in alias.lower():
                return info

    # 关键词匹配
    for key, info in FALLBACK_ATTRACTIONS.items():
        if key in query or query in key:
            return info

    return None


def _format_attraction_info(info: dict) -> str:
    """将景点信息格式化为适老化的文本输出"""
    lines = []
    lines.append("【%s】" % info.get("names", ["景点"])[0])
    lines.append("地址：%s" % info.get("location", "暂无"))
    lines.append("类型：%s" % info.get("category", "暂无"))
    lines.append("")
    lines.append("开放时间：")
    lines.append(info.get("opening_hours", "暂无"))
    lines.append("")
    lines.append("门票价格：")
    lines.append(info.get("ticket_prices", "暂无"))
    lines.append("")
    lines.append("交通指南：")
    lines.append(info.get("transportation", "暂无"))
    lines.append("")
    lines.append("主要看点：")
    lines.append(info.get("highlights", "暂无"))
    lines.append("")
    lines.append("老人温馨提示：")
    lines.append(info.get("elderly_tips", "暂无"))
    lines.append("")
    lines.append("景点介绍：")
    lines.append(info.get("description", "暂无"))
    return "\n".join(lines)


# ── 工具函数 ────────────────────────────────────────────

def attraction_guide(attraction_name: str) -> str:
    """
    查询景点详细导览信息

    参数：
        attraction_name: 景点名称（如故宫、长城、兵马俑、西湖等）
    """
    if not attraction_name or not attraction_name.strip():
        return "请告诉我您想了解哪个景点，例如：故宫、长城、兵马俑、西湖等。"

    query = attraction_name.strip()
    logger.info("景点导览查询: %s" % query)

    # 1. 先查向量知识库
    vectordb = _get_vectordb()
    if vectordb is not None:
        try:
            chunks = query_knowledge_base(query, top_k=4, vectordb=vectordb)
            if chunks:
                logger.info("向量库命中，返回 %d 个片段" % len(chunks))
                result = "\n\n---\n\n".join(chunks)
                result += "\n\n以上信息来自知识库检索。如需更详细的信息，欢迎进一步提问。"
                return result
        except Exception as e:
            logger.warning("向量库查询失败: %s" % e)

    # 2. 回退到内置知识库
    matched = _match_fallback(query)
    if matched:
        logger.info("内置知识库命中: %s" % matched["names"][0])
        return _format_attraction_info(matched)

    # 3. 都没匹配到
    known = "、".join(
        info["names"][0] for info in FALLBACK_ATTRACTIONS.values()
    )
    return (
        "抱歉，目前没有找到\"%s\"的详细信息。\n\n"
        "目前内置知识库覆盖的景点包括：\n%s\n\n"
        "您可以尝试查询以上景点，或者换一种方式描述您想了解的景点。"
        "我们也在持续更新景点数据库，感谢您的理解。"
        % (query, known)
    )


