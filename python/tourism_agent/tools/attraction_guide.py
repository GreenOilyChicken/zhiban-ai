# ── 线程安全的向量库访问 ────────────────────────────────

_vectordb: Any = None
_vectordb_lock = threading.Lock()


def _get_vectordb() -> Any:
    """线程安全地获取向量库实例（惰性初始化）"""
    global _vectordb
    if _vectordb is not None:
        return _vectordb
    with _vectordb_lock:
        if _vectordb is not None:
            return _vectordb
        try:
            db = load_knowledge_base(
                collection_name="tourism",
                persist_dir=config.KB_CHROMA_DIR,
            )
            _vectordb = db
            if db is not None:
                logger.info("景点向量库已加载")
            else:
                logger.info("景点向量库不存在，将使用内置知识库")
        except Exception as e:
            logger.warning(f"加载景点向量库失败: {e}，将使用内置知识库")
        return _vectordb


def _reset_vectordb():
    """重置向量库缓存（用于重建知识库后刷新）"""
    global _vectordb
    with _vectordb_lock:
        _vectordb = None


